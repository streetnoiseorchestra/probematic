(ns app.util.zip
  "Helpers for streaming ZIP files in HTTP responses.

  The application uses these functions when it needs to bundle generated or
  filestore-backed content without first materializing a complete archive on disk."
  (:require
   [clojure.java [io :as io]]
   [clojure.string :as s])
  (:import
   [java.io
    InputStream
    PipedInputStream
    PipedOutputStream]
   [java.nio.charset StandardCharsets]
   [java.text Normalizer Normalizer$Form]
   [java.util.zip ZipEntry ZipOutputStream]))

(defn de-accent
  "Returns `text` with Unicode accent marks removed.

  Returns `nil` when `text` is nil."
  [^String text]
  (when text
    (let [normalized (Normalizer/normalize text Normalizer$Form/NFD)]
      (s/replace normalized #"\p{InCombiningDiacriticalMarks}+" ""))))

(defn encode-filename
  "Returns a ZIP-entry-safe filename derived from `unencoded-filename`.

  The result keeps ASCII letters, numbers, dots, hyphens, underscores, and spaces.
  Accent marks are removed and all other characters are replaced with `-`.
  This avoids UTF-8 filename compatibility problems in ZIP tools."
  ^String [unencoded-filename]
  (when-let [de-accented (de-accent unencoded-filename)]
    (s/replace
     de-accented
     #"[^a-zA-Z0-9\.\-_ ]" "-")))

