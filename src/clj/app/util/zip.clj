(defn append-stream!
  "Appends input stream `in` to `zip` as a file named `file-name`.

  The entry name is normalized with [[encode-filename]].
  This function closes the ZIP entry, but it does not close `in` or `zip`.
  Returns `zip`.
  When `in` is nil, this is a no-op."
  [^ZipOutputStream zip file-name in]
  (when in
    (.putNextEntry zip (ZipEntry. (encode-filename file-name)))
    (io/copy in zip)
    (.closeEntry zip))
  zip)

(defn open-and-append!
  "Opens `(content-thunk)` and appends its bytes to `zip` as `file-name`.

  `content-thunk` must return an `InputStream`.
  The input stream is closed after copying.
  The ZIP stream is flushed so data can flow through streaming responses.
  Returns `zip`."
  [^ZipOutputStream zip file-name content-thunk]
  (with-open [in ^InputStream (content-thunk)]
    (append-stream! zip file-name in))
  ;; Flush after each attachment to ensure data flows into the output pipe
  (.flush zip)
  zip)

(defn piped-zip-input-stream
  "Returns an input stream for a ZIP archive generated by `content-fn`.

  `content-fn` receives a `ZipOutputStream` and runs in a future while callers read
  from the returned `InputStream`.
  The caller owns and must close the returned stream."
  ^InputStream [content-fn]
  (let [pos (PipedOutputStream.)
        ;; Use 16 MB pipe buffer
        is (PipedInputStream. pos 16777216)
        zip (ZipOutputStream. pos StandardCharsets/UTF_8)]
    (future
      ;; This runs in a separate thread so that the input stream can be returned immediately
      (try
        (content-fn zip)
        (.finish zip)
        (.flush zip)
        (catch Throwable t
          (throw (ex-info "Error occurred while generating ZIP output stream" {:msg (.getMessage t)} t)))
        (finally
          (.close zip)
          (.close pos))))
    is))

#_(defn- append-attachments-to-zip! [zip  attachments file-name-prefix]
    (doseq [{:keys [content file-name]} attachments]
      (when (and content file-name)
        (open-and-append! zip (str file-name-prefix "_" file-name) content))))

